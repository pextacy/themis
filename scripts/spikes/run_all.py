"""Run the Phase 0 spikes, write receipts, regenerate docs/READINESS.md.

    uv run scripts/spikes/run_all.py              # every spike
    uv run scripts/spikes/run_all.py guardrail    # one spike, by NAME

Exit code: 0 when the Phase 0 gate is met, 1 otherwise.
"""

from __future__ import annotations

import json
import sys
from typing import Any

import httpx
import s01_catalog
import s02_chat_model_a
import s03_chat_model_b
import s04_web
import s05_code_exec
import s06_mcp
import s07_guardrail
import s08_key_budget
import s09_per_user_budget
import s10_routing
from _common import REPO_ROOT, Blocked, Context, Failed, redact

SPIKES = (s01_catalog, s02_chat_model_a, s03_chat_model_b, s04_web, s05_code_exec,
          s06_mcp, s07_guardrail, s08_key_budget, s09_per_user_budget, s10_routing)

ADVANCED_NEEDED = 6
# Rubric feature -> spikes that must pass, and whether it counts as advanced.
RUBRIC: tuple[tuple[str, tuple[str, ...], bool], ...] = (
    ("Open-weight model", ("chat-model-a",), False),
    ("Second open-weight role", ("chat-model-b",), False),
    ("Routing & fallback", ("routing-fallback",), True),
    ("MCP", ("mcp-deepwiki",), True),
    ("Web search / fetch", ("web-search-fetch",), True),
    ("Code execution", ("code-execution",), True),
    ("Budgets", ("key-budget-refusal",), True),
    ("Multiple model roles", ("chat-model-a", "chat-model-b"), True),
    ("Inference guardrails", ("guardrail",), True),
    ("Per-user budgets", ("per-user-budget",), True),
)


def execute(ctx: Context, spike: Any) -> dict[str, Any]:
    ctx.calls = []
    result: dict[str, Any] = {"spike": spike.NAME, "at": ctx.now(), "base_url": ctx.base_url}
    try:
        result["observed"] = spike.run(ctx)
        result["status"] = "PASS"
    except Blocked as error:
        result.update(status="BLOCKED", reason=str(error))
    except Failed as error:
        result.update(status="FAIL", reason=str(error))
    except httpx.HTTPError as error:
        result.update(status="FAIL", reason=f"{type(error).__name__}: {error}")
    result["calls"] = ctx.calls
    return redact(result, ctx.secrets)


def stored_results(ctx: Context) -> dict[str, dict[str, Any]]:
    stored: dict[str, dict[str, Any]] = {}
    for spike in SPIKES:
        path = ctx.receipts_dir / f"{spike.NAME}.json"
        if path.exists():
            stored[spike.NAME] = json.loads(path.read_text())
    return stored


def readiness(results: dict[str, dict[str, Any]]) -> tuple[str, int, int]:
    icon = {"PASS": "✅", "FAIL": "⛔", "BLOCKED": "⛔", None: "⏳"}
    spike_rows = []
    for spike in SPIKES:
        result = results.get(spike.NAME, {})
        status = result.get("status")
        ids = [c["request_id"] for c in result.get("calls", []) if c.get("request_id")]
        evidence = f"`{ids[-1]}`" if ids else "—"
        reason = str(result.get("reason", "")).replace("|", "\\|")
        state = f"{icon.get(status, '⏳')} {status or 'NOT RUN'}"
        spike_rows.append(f"| `{spike.NAME}` | {state} | {evidence} | {reason} |")

    rubric_rows, advanced_ok, core_ok = [], 0, 0
    for feature, spikes, advanced in RUBRIC:
        statuses = [results.get(name, {}).get("status") for name in spikes]
        ok = all(status == "PASS" for status in statuses)
        advanced_ok += ok and advanced
        core_ok += ok and not advanced
        mark = "✅" if ok else ("⛔" if any(s in ("FAIL", "BLOCKED") for s in statuses) else "⏳")
        rubric_rows.append(f"| {feature} | {'advanced' if advanced else 'core'} | {mark} |")

    live = any(result.get("calls") for result in results.values())
    gate = "met" if advanced_ok >= ADVANCED_NEEDED and core_ok == 2 else "NOT met"
    text = "\n".join([
        "# Phase 0 readiness",
        "",
        "Generated by `scripts/spikes/run_all.py`. Do not edit by hand.",
        "",
        f"**Exit gate {gate}:** {advanced_ok} of 8 advanced features ✅ (need {ADVANCED_NEEDED}), "
        f"{core_ok} of 2 core features ✅.",
        "" if live else "\nNo live gateway call has been recorded yet.\n",
        "| Rubric feature | Kind | State |",
        "|---|---|---|",
        *rubric_rows,
        "",
        "| Spike | Result | Last request ID | Reason |",
        "|---|---|---|---|",
        *spike_rows,
        "",
    ])
    return text, advanced_ok, core_ok


def main(argv: list[str]) -> int:
    try:
        ctx = Context()
    except Failed as error:
        print(f"configuration error: {error}")
        return 1
    chosen = [s for s in SPIKES if not argv or s.NAME in argv]
    if argv and len(chosen) != len(argv):
        print(f"unknown spike. Known: {[s.NAME for s in SPIKES]}")
        return 1

    session: dict[str, dict[str, Any]] = {}
    fatal = None
    for spike in chosen:
        if fatal:
            session[spike.NAME] = {"spike": spike.NAME, "status": "BLOCKED", "reason": fatal, "calls": []}
        else:
            session[spike.NAME] = execute(ctx, spike)
        result = session[spike.NAME]
        print(f"{result['status']:8} {spike.NAME:22} {result.get('reason', '')}")
        if result["calls"]:
            ctx.save_json(f"{spike.NAME}.json", result)
        if spike is s01_catalog and result["status"] != "PASS":
            fatal = f"catalog spike did not pass: {result.get('reason')}"

    merged = {**stored_results(ctx), **session}
    text, advanced_ok, core_ok = readiness(merged)
    target = ctx.env.get("SPIKE_READINESS_PATH")
    path = REPO_ROOT / "docs" / "READINESS.md" if target is None else target
    with open(path, "w") as handle:
        handle.write(text)
    print(f"\nadvanced {advanced_ok}/8, core {core_ok}/2 -> {path}")
    return 0 if advanced_ok >= ADVANCED_NEEDED and core_ok == 2 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
